const alfabeto = "./0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"

func valorSalt(c byte) int {
	switch {
	case c >= 'a':
		return int(c-'a') + 38
	case c >= 'A':
		return int(c-'A') + 12
	case c >= '.':
		return int(c - '.')
	}
	return 0
}

// Crypt devolve o hash crypt(3) tradicional (13 caracteres: salt + 11).
func Crypt(senha, salt string) string {
	for len(salt) < 2 {
		salt += "."
	}
	// chave: 8 primeiros bytes, 7 bits cada, deslocados
	var chave [64]int
	for i := 0; i < 8 && i < len(senha); i++ {
		c := senha[i]
		for j := 0; j < 7; j++ {
			chave[i*8+j] = int(c>>(6-j)) & 1
		}
	}
	var cd [56]int
	for i := range pc1 {
		cd[i] = chave[pc1[i]-1]
	}
	var sub [16][48]int
	for r := 0; r < 16; r++ {
		for k := 0; k < shifts[r]; k++ {
			c0, d0 := cd[0], cd[28]
			copy(cd[0:27], cd[1:28])
			cd[27] = c0
			copy(cd[28:55], cd[29:56])
			cd[55] = d0
		}
		for i := range pc2 {
			sub[r][i] = cd[pc2[i]-1]
		}
	}
	e := eBox
	for i := 0; i < 2; i++ {
		v := valorSalt(salt[i])
		for j := 0; j < 6; j++ {
			if (v>>j)&1 == 1 {
				k := 6*i + j
				e[k], e[k+24] = e[k+24], e[k]
			}
		}
	}
	var bloco [64]int
	for it := 0; it < 25; it++ {
		var lr [64]int
		for i := range ip {
			lr[i] = bloco[ip[i]-1]
		}
		l := lr[:32]
		r := append([]int(nil), lr[32:]...)
		lcp := append([]int(nil), l...)
		for rodada := 0; rodada < 16; rodada++ {
			var x [48]int
			for i := 0; i < 48; i++ {
				x[i] = r[e[i]-1] ^ sub[rodada][i]
			}
			var s [32]int
			for b := 0; b < 8; b++ {
				o := b * 6
				lin := x[o]<<1 | x[o+5]
				col := x[o+1]<<3 | x[o+2]<<2 | x[o+3]<<1 | x[o+4]
				v := sBox[b][lin*16+col]
				for j := 0; j < 4; j++ {
					s[b*4+j] = (v >> (3 - j)) & 1
				}
			}
			nr := make([]int, 32)
			for i := 0; i < 32; i++ {
				nr[i] = lcp[i] ^ s[pBox[i]-1]
			}
			lcp, r = r, nr
		}
		var pre [64]int
		copy(pre[:32], r)
		copy(pre[32:], lcp)
		for i := range fp {
			bloco[i] = pre[fp[i]-1]
		}
	}
	out := []byte{salt[0], salt[1]}
	for i := 0; i < 11; i++ {
		v := 0
		for j := 0; j < 6; j++ {
			p := i*6 + j
			b := 0
			if p < 64 {
				b = bloco[p]
			}
			v = v<<1 | b
		}
		out = append(out, alfabeto[v])
	}
	return string(out)
}
